import { isWinterSeason } from "../seasonal-ranking.mjs";

// Pure helpers behind tools/refresh-winter-sales.mjs: turn ReAI's "Sales by product" report
// (invoice lines and POS receipts, online and physical store together) into units per product
// handle for the Men and Women pages.

const osloDate = new Intl.DateTimeFormat("en-CA", { timeZone: "Europe/Oslo", year: "numeric", month: "2-digit", day: "2-digit" });
export const osloDay = (date = new Date()) => osloDate.format(date); // YYYY-MM-DD

/** Report period for the current winter (1 October until today), or null outside the winter window. */
export function currentSeason(now = new Date()) {
  if (!isWinterSeason(now)) return null;
  const [year, month] = osloDay(now).split("-").map(Number);
  return { from: `${month >= 10 ? year : year - 1}-10-01`, to: osloDay(now) };
}

/** Size of a report line: from "(Size: 43.5)" in the name, else from a SKU such as "WS1UA02-003-43/5". */
export function sizeOf(line) {
  const named = /\(Size:\s*([\d.,]+)\)/i.exec(line.name || "");
  if (named) return Number(named[1].replace(",", "."));
  const coded = /-(\d{2})(\/5)?$/.exec(line.sku || "");
  return coded ? Number(coded[1]) + (coded[2] ? 0.5 : 0) : null;
}

/** Sizes 35-41 are counted as women's, 42-48 as men's; anything else is not attributed. */
export function audienceOf(size) {
  if (!Number.isFinite(size)) return null;
  if (size >= 35 && size < 42) return "women";
  if (size >= 42 && size <= 48) return "men";
  return null;
}

/**
 * @param {Array<{ productId: number | null, name?: string, sku?: string | null, quantity: number }>} items report rows
 * @param {Map<number, string>} handleByProductId storefront products
 */
export function aggregateSales(items, handleByProductId) {
  const units = { women: new Map(), men: new Map() };
  const stats = { linesUsed: 0, skippedNoProduct: 0, skippedNotStorefront: 0, skippedNoSize: 0 };
  for (const item of items) {
    // Wholesale invoices, shipping and rent have no product link; they are not shopper demand.
    if (item.productId == null) { stats.skippedNoProduct++; continue; }
    const handle = handleByProductId.get(item.productId);
    if (!handle) { stats.skippedNotStorefront++; continue; }
    const audience = audienceOf(sizeOf(item));
    if (!audience) { stats.skippedNoSize++; continue; }
    // Returns and credit notes arrive as negative quantities, so units are net.
    units[audience].set(handle, (units[audience].get(handle) || 0) + Number(item.quantity || 0));
    stats.linesUsed++;
  }
  const finish = (map) => Object.fromEntries([...map].map(([handle, count]) => [handle, Math.round(count)])
    .filter(([, count]) => count > 0)
    .sort((a, b) => b[1] - a[1] || a[0].localeCompare(b[0])));
  return { women: finish(units.women), men: finish(units.men), stats };
}

export function renderModule({ women, men }, { from, to, generatedOn, stats }) {
  const rows = (sales) => Object.entries(sales).map(([handle, count]) => `    ${JSON.stringify(handle)}: ${count},`).join("\n");
  const total = (sales) => Object.values(sales).reduce((sum, count) => sum + count, 0);
  return `// Units sold per product handle this winter, used to rank the Men and Women collection pages.
// Generated by sites/newmovements/tools/refresh-winter-sales.mjs; do not edit by hand.
//
// Source: ReAI "Sales by product" report, ${from} to ${to}, online and physical store together.
// - Only lines linked to a storefront product with a size are counted. Wholesale invoices,
//   shipping, rent and other brands have no such link and are left out.
// - Returns and credit notes are netted off.
// - Sizes 35-41 count as women's and 42-48 as men's (half sizes by their number).
//
// Women: ${Object.keys(women).length} products / ${total(women)} pairs. Men: ${Object.keys(men).length} products / ${total(men)} pairs.
// Report lines used: ${stats.linesUsed}. Skipped: ${stats.skippedNoProduct} without a product, ${stats.skippedNotStorefront} not storefront products, ${stats.skippedNoSize} without a 35-48 size.

export const WINTER_SALES_PERIOD = { from: "${from}", to: "${to}", generatedOn: "${generatedOn}" };

export const WINTER_SALES = {
  women: {
${rows(women)}
  },
  men: {
${rows(men)}
  },
};
`;
}
