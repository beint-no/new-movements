// Operator-only: brew install imagemagick libavif, then npm run optimize:images.
// Committed renditions make ordinary builds/deploys independent of native codecs.
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { mkdtemp, readFile, readdir, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const site = fileURLToPath(new URL('../sites/newmovements/', import.meta.url));
const root = join(site, 'public');
const manifestPath = join(site, 'editorial-image-manifest.mjs');
const temporary = await mkdtemp(join(tmpdir(), 'newmovements-images-'));
const manifest = {};
const files = (await readdir(join(root, 'brand-assets'), { recursive: true }))
  .filter((file) => /\.(jpe?g|png|webp)$/i.test(file) && file !== 'logo.png').sort();
let originalBytes = 0;
let fullSizeBytes = 0;
try {
  for (const file of files) {
    const source = join(root, 'brand-assets', file);
    const [width, height] = execFileSync('magick', [source, '-auto-orient', '-format', '%w %h', 'info:'], { encoding: 'utf8' }).trim().split(' ').map(Number);
    const renditions = [];
    for (const size of [...new Set([640, 960, 1440].map((size) => Math.min(size, width)))]) {
      const png = join(temporary, 'input.png');
      const avif = join(temporary, 'output.avif');
      execFileSync('magick', [source, '-auto-orient', '-colorspace', 'sRGB', '-resize', `${size}x>`, '-strip', png]);
      execFileSync('avifenc', ['-q', '65', '-s', '6', '-j', '2', '-y', '420', '--ignore-exif', '--ignore-xmp', png, avif], { stdio: 'pipe' });
      const bytes = await readFile(avif);
      const digest = createHash('sha256').update(bytes).digest('hex').slice(0, 16);
      const output = `${source}.${size}.${digest}.avif`;
      await writeFile(output, bytes);
      renditions.push({ width: size, url: `/${relative(root, output).split('\\').join('/')}` });
      if (size === Math.min(1440, width)) fullSizeBytes += bytes.length;
    }
    const sourceBytes = await readFile(source);
    originalBytes += sourceBytes.length;
    const sourceHash = createHash('sha256').update(sourceBytes).digest('hex');
    manifest[`/brand-assets/${file.split('\\').join('/')}`] = { width, height, renditions, sourceHash };
  }
  // Remove only obsolete generated renditions; preserve merchant originals.
  const keep = new Set(Object.values(manifest).flatMap((image) => image.renditions.map((item) => item.url)));
  for (const file of await readdir(join(root, 'brand-assets'), { recursive: true })) {
    const url = `/brand-assets/${file.split('\\').join('/')}`;
    if (/\.\d+\.[a-f0-9]{16}\.avif$/.test(file) && !keep.has(url)) await rm(join(root, url.slice(1)));
  }
  await writeFile(manifestPath, `// Generated by tools/optimize-editorial-images.mjs. Preserve source images.\nexport const EDITORIAL_IMAGES = ${JSON.stringify(manifest, null, 2)};\n`);
  console.log(`${files.length} editorial images: ${(originalBytes / 1024 / 1024).toFixed(1)} MB originals → ${(fullSizeBytes / 1024 / 1024).toFixed(1)} MB largest AVIF renditions.`);
} finally {
  await rm(temporary, { recursive: true, force: true });
}
